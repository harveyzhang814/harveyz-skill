import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "references"))

import workflow_resolve as wr  # noqa: E402

RULE = ".hskill/init-workflow/workflow-config.yml"

STAGING_CFG = """\
branches:
  protected:
    - name: main
      allow_direct_commit: false
      merge_from:
        - staging
        - "release/*"

    - name: staging
      allow_direct_commit: false
      merge_from:
        - "feature/*"
        - "fix/*"
        - "chore/*"
        - "doc/*"

branch_naming:
  enforce: true
  allowed_patterns:
    - "^feature/.+"
    - "^fix/.+"
    - "^chore/.+"
    - "^doc/.+"
    - "^release/[0-9]+\\\\.[0-9]+\\\\.[0-9]+(-.+)?$"
  exempt:                      # always exempt
    - main
    - staging

commit_message:
  enforce: true
  format: conventional
  conventional:
    types:
      - feat
      - fix
    max_subject_length: 80
"""

MAIN_ONLY_CFG = """\
branches:
  protected:
    - name: main
      allow_direct_commit: false
      merge_from:
        - "feature/*"

branch_naming:
  enforce: true
  allowed_patterns:
    - "^feature/.+"
  exempt:
    - main
"""

MASTER_CFG = """\
branches:
  protected:
    - name: master
      allow_direct_commit: false
      merge_from:
        - staging
    - name: staging
      allow_direct_commit: false
      merge_from:
        - "feature/*"

branch_naming:
  enforce: true
  allowed_patterns:
    - "^feature/.+"
  exempt:
    - master
    - staging
"""

NO_FEATURE_CFG = """\
branches:
  protected:
    - name: main
      allow_direct_commit: false
      merge_from:
        - "fix/*"

branch_naming:
  enforce: true
  allowed_patterns:
    - "^fix/.+"
  exempt:
    - main
"""


def write(tmp_path, text, rel="workflow-config.yml"):
    p = tmp_path / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text)
    return str(p)


def resolved_from(tmp_path, text):
    return wr.resolve(wr.load_config(write(tmp_path, text)), RULE)


def test_find_rule_file_prefers_primary_then_root_then_claude(tmp_path):
    root = str(tmp_path)
    assert wr.find_rule_file(root) is None
    write(tmp_path, "x: 1\n", ".claude/workflow-config.yml")
    assert wr.find_rule_file(root) == ".claude/workflow-config.yml"
    write(tmp_path, "x: 1\n", "workflow-config.yml")
    assert wr.find_rule_file(root) == "workflow-config.yml"
    write(tmp_path, "x: 1\n", ".hskill/init-workflow/workflow-config.yml")
    assert wr.find_rule_file(root) == ".hskill/init-workflow/workflow-config.yml"


def test_resolve_staging_gitflow(tmp_path):
    r = resolved_from(tmp_path, STAGING_CFG)
    assert r["integration_branches"] == ["main", "staging"]
    assert r["base"] == {
        "feature": "staging", "fix": "staging", "chore": "staging",
        "doc": "staging", "release": "main",
    }
    assert r["merge_target"] == "staging"
    assert r["merge_script"] == "scripts/merge-to-staging.sh"
    assert r["merge_trailer"] == "Merge-Via: merge-to-staging.sh"


def test_resolve_main_only(tmp_path):
    r = resolved_from(tmp_path, MAIN_ONLY_CFG)
    assert r["merge_target"] == "main"
    assert r["merge_script"] == "scripts/merge-to-main.sh"


def test_resolve_master_named_integration(tmp_path):
    r = resolved_from(tmp_path, MASTER_CFG)
    assert r["integration_branches"] == ["master", "staging"]


def test_defaults_when_worktree_and_merge_sections_absent(tmp_path):
    cfg = wr.load_config(write(tmp_path, STAGING_CFG))
    assert cfg["worktree_dir"] == ".worktrees"
    assert cfg["pre_checks"] == []
    r = wr.resolve(cfg, RULE)
    assert r["worktree_dir"] == ".worktrees"
    assert r["pre_checks"] == []


def test_custom_worktree_dir_and_pre_checks(tmp_path):
    text = STAGING_CFG + """
worktree:
  dir: wt

merge:
  pre_checks:
    - "node scripts/check-file-token-budget.js --changed-since {target}"
"""
    cfg = wr.load_config(write(tmp_path, text))
    assert cfg["worktree_dir"] == "wt"
    assert cfg["pre_checks"] == [
        "node scripts/check-file-token-budget.js --changed-since {target}"
    ]
    r = wr.resolve(cfg, RULE)
    assert r["worktree_dir"] == "wt"
    assert r["pre_checks"] == cfg["pre_checks"]


def test_no_base_feature_omits_merge_keys(tmp_path):
    r = resolved_from(tmp_path, NO_FEATURE_CFG)
    assert r["merge_target"] is None
    env = wr.format_env(r, "5.0.0")
    assert "merge_target=" not in env
    assert "merge_script=" not in env
    assert "merge_trailer=" not in env


def test_format_env_roundtrip(tmp_path):
    r = resolved_from(tmp_path, STAGING_CFG)
    text = wr.format_env(r, "5.0.0")
    assert text.startswith("# Generated by init-workflow 5.0.0")
    env = wr.parse_env(text)
    assert env["schema"] == "1"
    assert env["rule_file"] == RULE
    assert env["base.feature"] == "staging"
    assert env["naming.1"] == "^feature/.+"
    assert env["naming_exempt"] == "main staging"
    assert env["integration_branches"] == "main staging"
    assert env["merge_trailer"] == "Merge-Via: merge-to-staging.sh"
    assert env["worktree_dir"] == ".worktrees"
    # a '\\' escape in the YAML double-quoted pattern becomes a single backslash
    assert env["naming.5"] == r"^release/[0-9]+\.[0-9]+\.[0-9]+(-.+)?$"
