import os
import re
import subprocess
import sys

REFS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "references")
sys.path.insert(0, REFS)

import deploy_artifacts as da  # noqa: E402
import render_merge_script as rms  # noqa: E402
import workflow_resolve as wr  # noqa: E402

TEMPLATE_PATH = os.path.join(REFS, "merge-script-template.sh")

PRE_CHECK_1 = "node scripts/check-file-token-budget.js --changed-since {target}"
PRE_CHECK_2 = "python3 -m pytest -q"

CFG_HEAD = """\
branches:
  protected:
    - name: main
      allow_direct_commit: false
      merge_from:
        - staging
        - "release/*"

    - name: staging
      allow_direct_commit: false
      merge_from:
        - "feature/*"
        - "fix/*"

branch_naming:
  enforce: true
  allowed_patterns:
    - "^feature/.+"
    - "^fix/.+"
  exempt:
    - main
    - staging
"""

STAGING_CFG = CFG_HEAD + f"""
merge:
  pre_checks:
    - "{PRE_CHECK_1}"
    - "{PRE_CHECK_2}"
"""

MAIN_CFG = """\
branches:
  protected:
    - name: main
      allow_direct_commit: false
      merge_from:
        - "feature/*"

branch_naming:
  enforce: true
  allowed_patterns:
    - "^feature/.+"
  exempt:
    - main
"""

NO_FEATURE_CFG = """\
branches:
  protected:
    - name: main
      allow_direct_commit: false
      merge_from:
        - "fix/*"

branch_naming:
  enforce: true
  allowed_patterns:
    - "^fix/.+"
  exempt:
    - main
"""


def render_cfg(tmp_path, cfg_text):
    p = tmp_path / "workflow-config.yml"
    p.write_text(cfg_text)
    resolved = wr.resolve(wr.load_config(str(p)), "workflow-config.yml")
    with open(TEMPLATE_PATH, encoding="utf-8") as f:
        template = f.read()
    return rms.render_merge_script(resolved, template, "5.0.0")


def pre_checks_block(script):
    m = re.search(r"# --- BEGIN MANAGED: merge/pre-checks \(hash:[0-9a-f]{8}\) ---\n(.*?)# --- END MANAGED: merge/pre-checks ---",
                  script, re.S)
    assert m, "merge/pre-checks MANAGED block missing"
    return m.group(1)


def init_repo(path, cfg_text, rule="workflow-config.yml"):
    subprocess.run(["git", "init", "-q", "-b", "main", str(path)], check=True)
    (path / rule).write_text(cfg_text)


def test_target_and_trailer_rendered(tmp_path):
    script = render_cfg(tmp_path, STAGING_CFG)
    assert 'TARGET_BRANCH="staging"' in script
    assert "Merge-Via: merge-to-staging.sh" in script
    script = render_cfg(tmp_path, MAIN_CFG)
    assert 'TARGET_BRANCH="main"' in script
    assert "Merge-Via: merge-to-main.sh" in script
    assert "{{" not in script


def test_refuses_all_integration_branches(tmp_path):
    script = render_cfg(tmp_path, STAGING_CFG)
    assert 'INTEGRATION_BRANCHES="main staging"' in script
    assert "for integration_branch in $INTEGRATION_BRANCHES" in script


def test_pre_checks_block_rendered_in_order(tmp_path):
    script = render_cfg(tmp_path, STAGING_CFG)
    block = pre_checks_block(script)
    first = "run_pre_check 'node scripts/check-file-token-budget.js --changed-since staging'"
    second = "run_pre_check 'python3 -m pytest -q'"
    assert first in block and second in block
    assert block.index(first) < block.index(second)
    assert "{target}" not in block


def test_empty_pre_checks_block_has_no_commands(tmp_path):
    script = render_cfg(tmp_path, MAIN_CFG)
    assert pre_checks_block(script) == ""


def test_pre_check_with_single_quote_is_quoted_safely(tmp_path):
    cfg = MAIN_CFG + "\nmerge:\n  pre_checks:\n    - \"echo 'a b' && true\"\n"
    script = render_cfg(tmp_path, cfg)
    f = tmp_path / "m.sh"
    f.write_text(script)
    assert subprocess.run(["bash", "-n", str(f)]).returncode == 0
    assert "run_pre_check 'echo '\"'\"'a b'\"'\"' && true'" in pre_checks_block(script)


def test_generated_header_line(tmp_path):
    script = render_cfg(tmp_path, STAGING_CFG)
    lines = script.split("\n")
    assert lines[0].startswith("#!")
    assert lines[1] == ("# Generated by init-workflow 5.0.0; "
                        "edit merge.pre_checks in workflow-config.yml instead")


def test_deploy_writes_all_and_gitignore(tmp_path):
    init_repo(tmp_path, STAGING_CFG)
    first = da.deploy(str(tmp_path))
    assert ("NEW", ".hskill/init-workflow/resolved.env") in first
    assert ("NEW", "docs/reference/git-workflow.md") in first
    assert ("NEW", "scripts/merge-to-staging.sh") in first
    assert "scripts/merge-to-staging.sh" in [p for _, p in first]
    assert ".worktrees/" in (tmp_path / ".gitignore").read_text().splitlines()
    script = tmp_path / "scripts" / "merge-to-staging.sh"
    assert os.access(script, os.X_OK)
    assert (tmp_path / ".hskill/init-workflow/resolved.env").read_text().startswith(
        f"# Generated by init-workflow {wr.INIT_WORKFLOW_VERSION}")
    second = da.deploy(str(tmp_path))
    assert second and {s for s, _ in second} == {"UNCHANGED"}


def test_deploy_without_merge_target_skips_script(tmp_path):
    init_repo(tmp_path, NO_FEATURE_CFG)
    results = da.deploy(str(tmp_path))
    assert not list(tmp_path.glob("scripts/merge-to-*.sh"))
    assert not any(p.startswith("scripts/") for _, p in results)
    assert ("NEW", ".hskill/init-workflow/resolved.env") in results


def test_deploy_warns_on_unmarked_existing_script(tmp_path):
    init_repo(tmp_path, STAGING_CFG)
    script = tmp_path / "scripts" / "merge-to-staging.sh"
    script.parent.mkdir()
    script.write_text("#!/bin/sh\necho hand written\n")
    results = da.deploy(str(tmp_path))
    assert ("WARN", "scripts/merge-to-staging.sh") in results
    assert ("UPDATED", "scripts/merge-to-staging.sh") in results
    assert results.index(("WARN", "scripts/merge-to-staging.sh")) < results.index(("UPDATED", "scripts/merge-to-staging.sh"))
    assert "Generated by init-workflow" in script.read_text().split("\n")[1]
    # 再部署：已有生成标记 → 不再 WARN
    assert ("WARN", "scripts/merge-to-staging.sh") not in da.deploy(str(tmp_path))


def test_deploy_regenerates_script_with_generated_header_silently(tmp_path):
    init_repo(tmp_path, STAGING_CFG)
    da.deploy(str(tmp_path))
    script = tmp_path / "scripts" / "merge-to-staging.sh"
    script.write_text(script.read_text() + "# edited\n")
    results = da.deploy(str(tmp_path))
    assert ("UPDATED", "scripts/merge-to-staging.sh") in results
    assert not any(s == "WARN" for s, _ in results)


def test_deploy_gitignore_not_duplicated_when_already_ignored(tmp_path):
    init_repo(tmp_path, STAGING_CFG)
    (tmp_path / ".gitignore").write_text("node_modules/\n.worktrees/\n")
    results = da.deploy(str(tmp_path))
    assert ("UNCHANGED", ".gitignore") in results
    assert (tmp_path / ".gitignore").read_text() == "node_modules/\n.worktrees/\n"


def test_deploy_gitignore_appends_after_missing_trailing_newline(tmp_path):
    init_repo(tmp_path, STAGING_CFG)
    (tmp_path / ".gitignore").write_text("node_modules/")
    results = da.deploy(str(tmp_path))
    assert ("UPDATED", ".gitignore") in results
    assert (tmp_path / ".gitignore").read_text() == "node_modules/\n.worktrees/\n"


