#!/usr/bin/env python3
"""
init-workflow 一次性部署入口（Spec 5.4 a/b/c/e）
按序写出 resolved.env、docs/reference/git-workflow.md、标准合并脚本、.gitignore 条目，
逐项汇报 NEW / UPDATED / UNCHANGED / WARN。hooks 不在这里（由 agent 按 hook-templates.md 生成）。

用法：python3 deploy_artifacts.py <repo_root>
退出码：0 正常；2 找不到规则文件；3 配置解释不出必需取值（如受保护分支为空），未写任何产物
"""
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from workflow_resolve import (  # noqa: E402
    INIT_WORKFLOW_VERSION, ConfigError, find_rule_file, format_env, load_config, resolve,
)
from render_docs import carry_notes, render  # noqa: E402
from render_merge_script import render_merge_script  # noqa: E402

REFS = os.path.dirname(os.path.abspath(__file__))
ENV_PATH = '.hskill/init-workflow/resolved.env'
DOC_PATH = 'docs/reference/git-workflow.md'
GENERATED_MARK = '# Generated by init-workflow'


def _read(path):
    if not os.path.exists(path):
        return None
    with open(path, encoding='utf-8', newline='') as f:  # newline='' 保持字节原样
        return f.read()


def _write(path, text, executable=False):
    os.makedirs(os.path.dirname(path) or '.', exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='') as f:
        f.write(text)
    if executable:
        os.chmod(path, os.stat(path).st_mode | 0o111)


def _put(repo_root, rel, final, results, warn=False, executable=False):
    """差量写入一个产物；warn 为真时先追加 WARN（先于状态，与 render_docs.py 一致）。"""
    path = os.path.join(repo_root, rel)
    existing = _read(path)
    if warn:
        results.append(('WARN', rel))
    if existing == final:
        # 内容没变也保证脚本可执行
        if executable and not os.access(path, os.X_OK):
            os.chmod(path, os.stat(path).st_mode | 0o111)
        results.append(('UNCHANGED', rel))
        return
    _write(path, final, executable)
    results.append(('NEW' if existing is None else 'UPDATED', rel))


def _is_ignored(repo_root, worktree_dir):
    return subprocess.run(
        ['git', '-C', repo_root, 'check-ignore', '-q', worktree_dir + '/'],
        capture_output=True,
    ).returncode == 0


def deploy(repo_root):
    """返回 [(状态, 相对路径)]；没有规则文件时抛 FileNotFoundError，
    配置解释不出时抛 ConfigError（都在写任何产物之前）。"""
    rule_file = find_rule_file(repo_root)
    if rule_file is None:
        raise FileNotFoundError('找不到 workflow-config.yml（三级查找均不存在）')
    config = load_config(os.path.join(repo_root, rule_file))
    resolved = resolve(config, rule_file)
    results = []

    # a. resolved.env
    _put(repo_root, ENV_PATH, format_env(resolved, INIT_WORKFLOW_VERSION), results)

    # b. 工作流文档（自填区原样搬入；没有标记且内容不同 → WARN 后覆盖）
    with open(os.path.join(REFS, 'git-workflow-template.md'), encoding='utf-8') as f:
        rendered = render(config, resolved, f.read())
    final, warn = carry_notes(_read(os.path.join(repo_root, DOC_PATH)), rendered)
    if warn:
        print(f'WARN {DOC_PATH} 没有项目自填区标记，现有内容已被覆盖；'
              f'找回手改内容：git diff HEAD -- {DOC_PATH}', file=sys.stderr)
    _put(repo_root, DOC_PATH, final, results, warn=warn)

    # c. 标准合并脚本（只在有合并目标时）
    if resolved['merge_target']:
        with open(os.path.join(REFS, 'merge-script-template.sh'), encoding='utf-8') as f:
            script = render_merge_script(resolved, f.read(), INIT_WORKFLOW_VERSION)
        rel = resolved['merge_script']
        existing = _read(os.path.join(repo_root, rel))
        lines = existing.split('\n') if existing is not None else []
        has_mark = len(lines) > 1 and lines[1].startswith(GENERATED_MARK)
        warn = existing is not None and not has_mark and existing != script
        if warn:
            print(f'WARN {rel} 没有生成标记，现有内容已被覆盖；'
                  f'找回手改内容：git diff HEAD -- {rel}', file=sys.stderr)
        _put(repo_root, rel, script, results, warn=warn, executable=True)

    # e. .gitignore：worktree 目录未被忽略时追加一行
    wt = resolved['worktree_dir']
    gi_path = os.path.join(repo_root, '.gitignore')
    gi = _read(gi_path)
    if _is_ignored(repo_root, wt):
        results.append(('UNCHANGED', '.gitignore'))
    else:
        prefix = '' if not gi or gi.endswith('\n') else '\n'
        _write(gi_path, (gi or '') + prefix + wt + '/\n')
        results.append(('NEW' if gi is None else 'UPDATED', '.gitignore'))
    return results


if __name__ == '__main__':
    if len(sys.argv) != 2:
        print('用法：deploy_artifacts.py <repo_root>', file=sys.stderr)
        sys.exit(2)
    try:
        for status, rel in deploy(sys.argv[1]):
            print(f'{status} {rel}')
    except FileNotFoundError as e:
        print(f'ERROR {e}', file=sys.stderr)
        sys.exit(2)
    except ConfigError as e:
        print(f'ERROR {e}', file=sys.stderr)
        sys.exit(3)
