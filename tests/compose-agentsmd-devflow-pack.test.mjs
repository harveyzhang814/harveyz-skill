import test, { after } from 'node:test'
import assert from 'node:assert/strict'
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, readdirSync, rmSync, existsSync } from 'node:fs'
import { spawnSync } from 'node:child_process'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { runGenerate, runCheck } from '../skills/devflow/compose-agentsmd/scripts/lib/compose.mjs'

const packsDir = fileURLToPath(new URL('../skills/devflow/compose-agentsmd/assets/packs', import.meta.url))
const PACK = join(packsDir, 'devflow')
const tmpRoots = []
after(() => tmpRoots.forEach(d => rmSync(d, { recursive: true, force: true })))

const RESOLVED = 'merge_target=develop\nmerge_script=scripts/merge-to-develop.sh\n'

// 建临时根并写配置；resolvedEnv 为 null 时不写 resolved.env
function makeRoot(config, resolvedEnv = RESOLVED) {
  const root = mkdtempSync(join(tmpdir(), 'compose-agentsmd-devflow-'))
  tmpRoots.push(root)
  const dir = join(root, '.hskill/compose-agentsmd')
  mkdirSync(join(dir, 'slots'), { recursive: true })
  writeFileSync(join(dir, 'config.json'), JSON.stringify(config))
  if (resolvedEnv !== null) {
    mkdirSync(join(root, '.hskill/init-workflow'), { recursive: true })
    writeFileSync(join(root, '.hskill/init-workflow/resolved.env'), resolvedEnv)
  }
  return root
}

// 在临时根写配置、调用 runGenerate，返回生成的 AGENTS.md 文本
function generateWith(config, resolvedEnv = RESOLVED) {
  const root = makeRoot(config, resolvedEnv)
  const r = runGenerate({ root, packsDir })
  assert.equal(r.code, 0, (r.errors ?? []).join('\n'))
  return readFileSync(join(root, 'AGENTS.md'), 'utf8')
}

const CANVAS_WORDS = ['describe-node','capture-requirement','relate-node','observe-node-quality','judge-release','Agent Canvas','Step 8','画布','节点','第二道关','版本验收','V<n>｜']
const PROJECT_WORDS = ['Electron','simulate-user','sync-design','.design-scratch','staging','merge-to-staging','main↔renderer','.claude/worktrees','AGENTS.pre-init-spec','2026-10-13-requirement-acceptance']
const cfg = { title: 'P', pack: 'devflow' }

test('V2 agent_canvas false leaves no canvas wording but keeps acceptance criteria', () => {
  const text = generateWith({ ...cfg, agent_canvas: false })
  for (const w of CANVAS_WORDS) assert.ok(!text.includes(w), w)
  assert.ok(text.includes('## 验收标准'))
  assert.ok(!text.includes('slot:release-acceptance'))
})
test('V2 agent_canvas true includes Step 8, release acceptance and V format', () => {
  const text = generateWith({ ...cfg, agent_canvas: true })
  assert.ok(text.includes('## Step 8')); assert.ok(text.includes('## 版本验收')); assert.ok(text.includes('V1｜'))
})
test('V4 devflow pack files contain no Agent Canvas project specifics', () => {
  for (const f of readdirSync(PACK)) for (const w of PROJECT_WORDS)
    assert.ok(!readFileSync(join(PACK, f), 'utf8').includes(w), `${f}: ${w}`)
})
test('params are substituted into the flow', () => {
  const text = generateWith({ ...cfg, e2e: 'Playwright E2E', complexity_signals: '改动公共 API' })
  for (const v of ['develop', 'scripts/merge-to-develop.sh', 'Playwright E2E', '改动公共 API', 'docs/superpowers/specs']) assert.ok(text.includes(v), v)
  assert.ok(!text.includes('@{'))
})
test('pack.json matches the spec declaration', () => {
  const p = JSON.parse(readFileSync(join(PACK, 'pack.json'), 'utf8'))
  assert.deepEqual(p.slots, ['flow-summary','instruction-sources','platform-fallbacks','flow-steps','release-acceptance'])
  assert.deepEqual(p.linked, [['flow-summary','flow-steps']])
  assert.equal(readFileSync(join(PACK, 'VERSION'), 'utf8'), '2.1.0\n')
})
test('pack.json no longer declares integration_branch or merge_command', () => {
  const p = JSON.parse(readFileSync(join(PACK, 'pack.json'), 'utf8'))
  assert.ok(!('integration_branch' in p.params)); assert.ok(!('merge_command' in p.params))
  assert.equal(readFileSync(join(PACK, 'VERSION'), 'utf8'), '2.1.0\n')
})
test('integration branch comes from resolved.env merge_target', () => {
  const text = generateWith(cfg, 'merge_target=develop\nmerge_script=scripts/merge-to-develop.sh\n')
  assert.ok(text.includes('merge-base --is-ancestor HEAD develop'))
  const other = generateWith(cfg, '# Generated by init-workflow 5.0.0\r\n\r\nmerge_target=release\r\nmerge_script=scripts/merge-to-release.sh\r\n')
  assert.ok(other.includes('merge-base --is-ancestor HEAD release')); assert.ok(!other.includes('HEAD develop'))
})
test('missing resolved.env -> generate and check exit 2 naming init-workflow', () => {
  const root = makeRoot(cfg, null)
  const g = runGenerate({ root, packsDir })
  assert.equal(g.code, 2); assert.match(g.errors[0], /先运行 init-workflow/)
  assert.equal(existsSync(join(root, 'AGENTS.md')), false)
  const c = runCheck({ root, packsDir })
  assert.equal(c.code, 2); assert.match(c.errors[0], /先运行 init-workflow/)
})
test('resolved.env without merge_target -> exit 2', () => {
  const root = makeRoot(cfg, '# only a comment\nmerge_script=scripts/merge-to-develop.sh\n')
  const g = runGenerate({ root, packsDir })
  assert.equal(g.code, 2); assert.match(g.errors[0], /merge_target/); assert.match(g.errors[0], /先运行 init-workflow/)
  assert.equal(runCheck({ root, packsDir }).code, 2)
})
test('config still carrying merge_command or integration_branch -> exit 2 unknown field', () => {
  for (const key of ['merge_command', 'integration_branch']) {
    const root = makeRoot({ ...cfg, [key]: 'x' })
    const g = runGenerate({ root, packsDir })
    assert.equal(g.code, 2, key); assert.match(g.errors[0], /未知字段/); assert.ok(g.errors[0].includes(key))
    assert.match(g.errors[0], /删除/)
    assert.equal(runCheck({ root, packsDir }).code, 2, key)
  }
})
test('step 7 says manage-worktree merge with script fallback', () => {
  const text = generateWith(cfg)
  assert.ok(text.includes('manage-worktree「合并」'))
  assert.ok(text.includes('scripts/merge-to-develop.sh'))
  assert.ok(!text.includes('@{'))
})
test('merge_script is read from resolved.env, not derived from merge_target', () => {
  const text = generateWith(cfg, 'merge_target=develop\nmerge_script=scripts/custom-merge.sh\n')
  assert.ok(text.includes('scripts/custom-merge.sh'))
  assert.ok(!text.includes('scripts/merge-to-develop.sh'))
  assert.ok(text.includes('merge-base --is-ancestor HEAD develop'))
  // merge_script 缺省时才回退到 scripts/merge-to-<merge_target>.sh
  assert.ok(generateWith(cfg, 'merge_target=develop\n').includes('scripts/merge-to-develop.sh'))
})
test('compose sources never read workflow-config.yml', () => {
  const skillDir = fileURLToPath(new URL('../skills/devflow/compose-agentsmd', import.meta.url))
  for (const sub of ['scripts', 'assets']) {
    const r = spawnSync('grep', ['-rn', 'workflow-config', join(skillDir, sub)], { encoding: 'utf8' })
    assert.equal(r.status, 1, r.stdout)
  }
})
